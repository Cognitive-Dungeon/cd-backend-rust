//! Система зон попадания (Hit Locations) для BRP/Bevy.
//!
//! Этот модуль реализует механику выбора зоны попадания по гуманоиду
//! согласно правилам **Basic Roleplaying Universal Game Engine (BRP UGE)**.
//! Каждая зона имеет уникальные свойства, влияющие на:
//! - Распределение урона по частям тела
//! - Расчёт максимальных ХП для конкретной зоны
//! - Применение специфичных эффектов (переломы, кровотечения, смерть)
//!
//! # Механика броска D20
//! Зона попадания определяется броском 1d20 с фиксированными диапазонами:
//! ```text
//!  1-4  : Правая нога  (20% шанс)
//!  5-8  : Левая нога   (20% шанс)
//!  9-11 : Живот        (15% шанс)
//!  12   : Грудь        (5% шанс)  ← критическая зона
//! 13-15 : Правая рука  (15% шанс)
//! 16-18 : Левая рука   (15% шанс)
//! 19-20 : Голова       (10% шанс) ← критическая зона
//! ```
//!
//! # Распределение ХП по зонам (BRP UGE, стр. 14)
//! | Зона | Доля от общих ХП | Обоснование |
//! |------|-----------------|-------------|
//! | Ноги | 1/3 (~33%) | Большая масса, но не критичны для выживания |
//! | Руки | 1/4 (25%) | Меньшая масса, важны для манипуляций |
//! | Живот | 1/3 (~33%) | Содержит органы, но защищён мышцами |
//! | Грудь | 4/10 (40%) | Сердце и лёгкие — высокая критичность |
//! | Голова | 1/3 (~33%) | Мозг — мгновенная смерть при уничтожении |
//!
//! > **Примечание**: Сумма долей превышает 100%, так как ХП зон рассчитываются
//! > независимо от общих ХП. Это позволяет частям тела "переживать" смерть тела
//! > в симулятивных системах (например, для механики ампутаций).
//!
//! # Интеграция с Bevy Reflect
//! Тип `HitLocationType` реализует `Reflect` для:
//! - Сериализации в сохранении игры
//! - Отображения в редакторе/инспекторе
//! - Сетевой репликации через `lightyear`/`bevy_replicon`
//!
//! # Пример использования
//! ```rust,ignore
//! use crate::anatomy::{HitLocationType, HitLocationRoll};
//!
//! // Бросок кубика в бою
//! let d20_roll = rng.random_range(1..=20);
//! let location = HitLocationType::roll_humanoid(d20_roll);
//!
//! // Расчёт ХП для зоны
//! let total_hp = 12; // CON+SIZ/2 по BRP
//! let location_max_hp = (total_hp as f32 * location.hp_fraction()).ceil() as i32;
//!
//! // Применение урона к анатомии
//! anatomy.apply_damage(location, raw_damage);
//! ```
//!
//! # Источники
//! - *Basic Roleplaying UGE*, стр. 14: "Hit Locations", "Major Wounds"
//! - *Dwarf Fortress*: механика `BODY_PART` и распределение урона
//! - *CDDA*: система зон попадания с модификаторами точности

use bevy::reflect::Reflect;
use enum_map::Enum;
use serde::{Deserialize, Serialize};

/// Зоны попадания по гуманоиду согласно таблице BRP UGE.
///
/// # Архитектурное назначение
/// `HitLocationType` служит ключом для:
/// - Индексации частей тела в `HashMap<HitLocationType, BodyPart>`
/// - Выборки модификаторов брони по зоне
/// - Применения специфичных эффектов (например, `Head` → игнор брони при крите)
///
/// # Критические зоны
/// Некоторые зоны требуют особой обработки в логике смерти:
/// ```rust,ignore
/// // В Anatomy::is_alive()
/// const CRITICAL_ZONES: [HitLocationType; 3] = [
///     HitLocationType::Head,
///     HitLocationType::Chest,
///     HitLocationType::Abdomen,
/// ];
///
/// for zone in CRITICAL_ZONES {
///     if let Some(part) = anatomy.parts.get(&zone) {
///         if part.is_destroyed() {
///             return false; // Смерть при уничтожении критической зоны
///         }
///     }
/// }
/// ```
///
/// # Взаимодействие с другими системами
/// | Система | Использование HitLocationType |
/// |---------|------------------------------|
/// | `combat::damage` | Выбор зоны при попадании |
/// | `anatomy::BodyPart` | Ключ для хранения данных части |
/// | `encumbrance` | Штрафы при повреждении ног/рук |
/// | `action_points` | Расчёт доступных действий при травмах |
///
/// # Пример сериализации
/// ```rust,ignore
/// // При сохранении игры
/// let json = serde_json::to_string(&HitLocationType::LeftArm)?;
/// // Результат: "LeftArm" (благодаря #[serde(...)])
///
/// // При загрузке
/// let location: HitLocationType = serde_json::from_str("\"Head\"")?;
/// ```
///
/// # Ссылки
/// - *BRP UGE*, стр. 14: таблица "Humanoid Hit Locations"
/// - *BRP UGE*, стр. 15: последствия "Major Wounds" по зонам
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, Reflect, Enum)]
#[serde(rename_all = "PascalCase")]
pub enum HitLocationType {
    /// Правая нога: опорная конечность для движения и баланса.
    ///
    /// # Механика
    /// - **Диапазон броска**: 1-4 на d20 (20% шанс попадания)
    /// - **Доля ХП**: 1/3 от общих (~33%)
    /// - **Критичность**: Низкая (потеря функции, но не смерть)
    ///
    /// # Геймплейные эффекты при повреждении
    /// | Состояние | Эффект |
    /// |-----------|--------|
    /// | `Fractured` | MOV/2, штраф -50% к физическим навыкам |
    /// | `Severed` | Невозможно стоять/ходить, штраф -75% ко всем действиям |
    /// | `Destroyed` | Автоматическая проверка на падение (Prone) |
    ///
    /// # Тактическое значение
    /// - Целенаправленные атаки в ногу могут обездвижить противника
    /// - Эффективно против тяжёлой брони (ноги часто менее защищены)
    /// - Риск: противник может упасть, но продолжит атаковать из положения лёжа
    ///
    /// # Пример из правил
    /// > "A character with a broken leg moves at half speed and cannot run."
    /// — BRP UGE, адаптировано для симулятивной модели
    RightLeg,

    /// Левая нога: опорная конечность для движения и баланса.
    ///
    /// # Механика
    /// Идентична `RightLeg` за исключением:
    /// - **Диапазон броска**: 5-8 на d20 (20% шанс)
    /// - В леворуких персонажей может иметь иные анимации (косметически)
    ///
    /// # Симметрия в коде
    /// Для упрощения логики обе ноги обрабатываются одинаково:
    /// ```rust,ignore
    /// let legs = [HitLocationType::LeftLeg, HitLocationType::RightLeg];
    /// let any_leg_broken = legs.iter().any(|&leg| {
    ///     anatomy.parts.get(&leg).is_some_and(|p| p.is_useless())
    /// });
    /// ```
    ///
    /// # Расширение: доминантная нога
    /// В будущих версиях можно добавить параметр `dominant_leg` для:
    /// - Разных штрафов при повреждении опорной/толчковой ноги
    /// - Особых анимаций атаки/защиты
    LeftLeg,

    /// Живот: зона брюшной полости с внутренними органами.
    ///
    /// # Механика
    /// - **Диапазон броска**: 9-11 на d20 (15% шанс)
    /// - **Доля ХП**: 1/3 от общих (~33%)
    /// - **Критичность**: Средняя (риск внутренних повреждений)
    ///
    /// # Содержимое зоны
    /// При симулятивной анатомии живот содержит:
    /// - Желудок, кишечник (пищеварение)
    /// - Печень, поджелудочная (детоксикация)
    /// - Крупные сосуды (риск кровотечения)
    ///
    /// # Геймплейные эффекты при повреждении
    /// | Состояние | Эффект |
    /// |-----------|--------|
    /// | `Bleeding` | Внутреннее кровотечение: 2 ХП/раунд, сложно остановить |
    /// | `Fractured` | Штраф -30% к выносливости, боль при движении |
    /// | `Severed` | Разрыв органов: автоматическая проверка на смерть |
    ///
    /// # Лечение
    /// - Поверхностные раны: стандартное лечение
    /// - Внутренние повреждения: требует навыка **Surgery** или магии
    /// - Кровотечение: сложно обнаружить, риск смерти без диагностики
    ///
    /// # Пример из правил
    /// > "Abdominal wounds may cause internal bleeding, requiring immediate medical attention."
    /// — Адаптировано из расширенных правил BRP
    Abdomen,

    /// Грудь: зона сердца, лёгких и защиты позвоночника.
    ///
    /// # Механика
    /// - **Диапазон броска**: 12 на d20 (5% шанс) ← наименее вероятна
    /// - **Доля ХП**: 4/10 от общих (40%) ← наибольшая доля
    /// - **Критичность**: Высокая (уничтожение = мгновенная смерть)
    ///
    /// # Содержимое зоны
    /// Критические органы:
    /// - **Сердце**: остановка = смерть за 1-3 раунда
    /// - **Лёгкие**: повреждение = гипоксия, штраф к действиям
    /// - **Крупные сосуды**: аорта, полые вены (массивное кровотечение)
    /// - **Позвоночник**: повреждение = паралич ниже уровня травмы
    ///
    /// # Особые правила
    /// - **Броня**: грудь обычно имеет наивысшую защиту (латы, кираса)
    /// - **Критический удар**: игнорирует броню, макс. урон
    /// - **Impaling оружие**: удваивает базовый урон при попадании в грудь
    ///
    /// # Геймплейные эффекты при повреждении
    /// | Состояние | Эффект |
    /// |-----------|--------|
    /// | `Bleeding` | Кровотечение в грудную полость: 3 ХП/раунд, риск удушья |
    /// | `Fractured` | Перелом рёбер: боль при дыхании, -20% к выносливости |
    /// | `Severed` | Разрыв сердца/лёгких: автоматическая смерть |
    ///
    /// # Пример из правил
    /// > "A critical hit to the chest ignores armor and deals maximum damage."
    /// — BRP UGE, стр. 149
    Chest,

    /// Правая рука: конечность для атаки, защиты и манипуляций.
    ///
    /// # Механика
    /// - **Диапазон броска**: 13-15 на d20 (15% шанс)
    /// - **Доля ХП**: 1/4 от общих (25%)
    /// - **Критичность**: Низкая (потеря функции, но не смерть)
    ///
    /// # Геймплейные эффекты при повреждении
    /// | Состояние | Эффект |
    /// |-----------|--------|
    /// | `Fractured` | Невозможно держать оружие двумя руками, штраф -50% к атаке |
    /// | `Severed` | Выпадение предмета из руки, невозможность атаковать этой рукой |
    /// | `Destroyed` | Постоянная потеря функции, требует протеза/магии для восстановления |
    ///
    /// # Доминантная рука
    /// Для правшей (по умолчанию):
    /// - Повреждение правой руки: штраф к основной атаке
    /// - Повреждение левой руки: штраф к парированию/второй атаке
    ///
    /// # Пример использования в бою
    /// ```rust,ignore
    /// // Проверка: может ли персонаж атаковать?
    /// let can_attack = anatomy.parts.get(&HitLocationType::RightArm)
    ///     .is_some_and(|arm| !arm.is_useless());
    ///
    /// if !can_attack {
    ///     // Переключиться на левую руку или использовать альтернативные действия
    /// }
    /// ```
    RightArm,

    /// Левая рука: конечность для парирования, второй атаки и манипуляций.
    ///
    /// # Механика
    /// Идентична `RightArm` за исключением:
    /// - **Диапазон броска**: 16-18 на d20 (15% шанс)
    /// - Для левшей: является доминантной (основная атака)
    ///
    /// # Тактическое значение
    /// - Левая рука часто держит щит → повреждение снижает защиту
    /// - Двумя руками: повреждение любой руки = штраф к урону
    /// - Заклинатели: повреждение руки может нарушить вербальные/соматические компоненты
    ///
    /// # Пример: парирование с повреждённой рукой
    /// ```rust,ignore
    /// // В системе парирования
    /// let parry_bonus = if anatomy.parts.get(&HitLocationType::LeftArm)
    ///     .is_some_and(|arm| arm.is_useless())
    /// {
    ///     -50 // Штраф 50% к парированию
    /// } else {
    ///     0
    /// };
    /// ```
    LeftArm,

    /// Голова: зона мозга, органов чувств и критических нервов.
    ///
    /// # Механика
    /// - **Диапазон броска**: 19-20 на d20 (10% шанс)
    /// - **Доля ХП**: 1/3 от общих (~33%)
    /// - **Критичность**: Максимальная (уничтожение = мгновенная смерть)
    ///
    /// # Содержимое зоны
    /// Критические структуры:
    /// - **Мозг**: контроль всех функций, повреждение = смерть/паралич
    /// - **Глаза**: зрение, повреждение = штраф к восприятию/атаке
    /// - **Уши**: слух и баланс, повреждение = штраф к инициативе
    /// - **Череп**: защита мозга, перелом = риск внутреннего кровотечения
    ///
    /// # Особые правила
    /// - **Размер**: малая цель, штраф к попаданию (-20% в некоторых системах)
    /// - **Броня**: шлемы обеспечивают защиту, но часто имеют "слепые зоны"
    /// - **Критический удар**: автоматическая смерть при уроне ≥ макс. ХП головы
    ///
    /// # Геймплейные эффекты при повреждении
    /// | Состояние | Эффект |
    /// |-----------|--------|
    /// | `Bleeding` | Кровотечение из головы: 1 ХП/раунд, риск потери сознания |
    /// | `Fractured` | Сотрясение: штраф -30% ко всем навыкам, риск потери сознания |
    /// | `Severed` | Разрушение мозга: мгновенная смерть |
    ///
    /// # Сенсорные штрафы
    /// При симулятивной анатомии повреждение головы может вызывать:
    /// ```rust,ignore
    /// match injury {
    ///     Injury::Fractured => {
    ///         // Сотрясение
    ///         vitals.consciousness *= 0.7;
    ///         skills.apply_penalty(-30);
    ///     }
    ///     Injury::Severed => {
    ///         // Смерть
    ///         return CharacterState::Dead;
    ///     }
    ///     _ => {}
    /// }
    /// ```
    ///
    /// # Пример из правил
    /// > "A hit to the head that reduces it to 0 HP or less causes instant death."
    /// — BRP UGE, стр. 15
    Head,
}

/// Trait для операций с зонами попадания по правилам BRP.
///
/// # Назначение
/// `HitLocationRoll` инкапсулирует логику:
/// - Преобразования броска кубика в зону попадания
/// - Расчёта доли ХП для конкретной зоны
///
/// Это позволяет легко заменять реализацию для:
/// - Негуманоидных существ (другие таблицы бросков)
/// - Модификаторов точности (прицельные атаки в конкретную зону)
/// - Вариативных правил (домашние кампании с иными таблицами)
///
/// # Пример расширения для не-гуманоидов
/// ```rust,ignore
/// // Для четвероногих существ
/// impl HitLocationRoll for QuadrupedLocation {
///     fn roll_humanoid(d20: i32) -> Self {
///         // Другая таблица распределения
///         match d20 {
///             1..=6 => Self::FrontLeg,
///             7..=12 => Self::Body,
///             13..=18 => Self::HindLeg,
///             _ => Self::Head,
///         }
///     }
///
///     fn hp_fraction(&self) -> f32 {
///         // Иные пропорции для животного тела
///         match self {
///             Self::Body => 0.5, // Тело содержит больше массы
///             Self::Head => 0.2,
///             _ => 0.15,
///         }
///     }
/// }
/// ```
///
/// # Ссылки
/// - *BRP UGE*, стр. 14: базовая таблица для гуманоидов
/// - *BRP UGE*, стр. 148: модификаторы для прицельных атак
pub trait HitLocationRoll {
    /// Бросок D20 для выбора зоны попадания по гуманоиду (BRP).
    ///
    /// # Параметры
    /// - `d20`: результат броска 1d20 (диапазон 1..=20)
    ///
    /// # Возвращаемое значение
    /// `HitLocationType` соответствующий выпавшему диапазону.
    ///
    /// # Валидация входных данных
    /// Функция не проверяет диапазон `d20` — caller обязан обеспечить
    /// корректное значение. Для отладки можно добавить:
    /// ```rust,ignore
    /// debug_assert!((1..=20).contains(&d20), "Invalid d20 roll: {}", d20);
    /// ```
    ///
    /// # Пример использования
    /// ```rust,ignore
    /// use crate::anatomy::{HitLocationType, HitLocationRoll};
    ///
    /// let roll = rng.random_range(1..=20);
    /// let location = HitLocationType::roll_humanoid(roll);
    ///
    /// // Или через трейт-объект для полиморфизма
    /// let location: Box<dyn HitLocationRoll> = get_location_table(creature_type);
    /// let result = location.roll_humanoid(roll);
    /// ```
    ///
    /// # Производительность
    /// Функция инлайнится компилятором (`#[inline]` неявно для тривиальных `match`),
    /// что минимизирует накладные расходы в горячих путях боевой системы.
    fn roll_humanoid(d20: i32) -> Self;

    /// Доля от общего пула ХП для этой части тела (правила BRP, стр. 14).
    ///
    /// # Возвращаемое значение
    /// Дробное значение (0.0-1.0), представляющее долю общих ХП,
    /// выделяемую для данной зоны. Используется для расчёта:
    /// ```rust,ignore
    /// let location_max_hp = (total_hp as f32 * location.hp_fraction()).ceil() as i32;
    /// ```
    ///
    /// # Обоснование значений
    /// | Зона | Доля | Обоснование по правилам |
    /// |------|------|------------------------|
    /// | Ноги | 1/3 | Большая масса, но не критичны |
    /// | Руки | 1/4 | Меньшая масса, важны для действий |
    /// | Живот | 1/3 | Содержит органы, средняя защита |
    /// | Грудь | 4/10 | Критические органы, высокая защита |
    /// | Голова | 1/3 | Малый размер, но максимальная критичность |
    ///
    /// # Округление
    /// При расчёте ХП зоны используется `ceil()` (округление вверх),
    /// чтобы гарантировать минимум 1 ХП даже для слабых персонажей:
    /// ```rust,ignore
    /// // Персонаж с 3 общими ХП
    /// let total = 3;
    /// let arm_hp = (3.0 * 0.25).ceil() as i32; // = 1, а не 0
    /// ```
    ///
    /// # Расширение: кастомные пропорции
    /// Для балансировки под конкретный сеттинг можно переопределить:
    /// ```rust,ignore
    /// // В конфиге игры
    /// pub struct LocationConfig {
    ///     pub head_fraction: f32,   // По умолчанию: 1.0/3.0
    ///     pub chest_fraction: f32,  // По умолчанию: 4.0/10.0
    ///     // ...
    /// }
    ///
    /// // Использование
    /// let config = load_config();
    /// let head_hp = (total_hp as f32 * config.head_fraction).ceil() as i32;
    /// ```
    fn hp_fraction(&self) -> f32;
}

impl HitLocationRoll for HitLocationType {
    fn roll_humanoid(d20: i32) -> Self {
        // Таблица соответствует BRP UGE, стр. 14
        // Диапазоны выбраны так, чтобы сумма вероятностей = 100%
        match d20 {
            1..=4 => Self::RightLeg,   // 4/20 = 20%
            5..=8 => Self::LeftLeg,    // 4/20 = 20%
            9..=11 => Self::Abdomen,   // 3/20 = 15%
            12 => Self::Chest,         // 1/20 = 5%
            13..=15 => Self::RightArm, // 3/20 = 15%
            16..=18 => Self::LeftArm,  // 3/20 = 15%
            _ => Self::Head,           // 2/20 = 10% (19-20)
        }
    }

    fn hp_fraction(&self) -> f32 {
        // Доли соответствуют таблице "Hit Location HP" в BRP UGE, стр. 14
        // Значения возвращаются как float для точного расчёта с ceil()
        match self {
            // Группировка по одинаковым значениям для оптимизации
            Self::RightLeg | Self::LeftLeg | Self::Abdomen | Self::Head => 1.0 / 3.0,
            Self::Chest => 4.0 / 10.0,
            Self::RightArm | Self::LeftArm => 1.0 / 4.0,
        }
    }
}

