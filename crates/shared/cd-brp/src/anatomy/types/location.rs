#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_roll_humanoid_distribution() {
        // Проверка: все значения 1..=20 маппятся корректно
        let cases = [
            (1..=4, HitLocationType::RightLeg),
            (5..=8, HitLocationType::LeftLeg),
            (9..=11, HitLocationType::Abdomen),
            (12..=12, HitLocationType::Chest),
            (13..=15, HitLocationType::RightArm),
            (16..=18, HitLocationType::LeftArm),
            (19..=20, HitLocationType::Head),
        ];

        for (range, expected) in cases {
            for roll in range {
                assert_eq!(
                    HitLocationType::roll_humanoid(roll),
                    expected,
                    "Roll {} should map to {:?}",
                    roll,
                    expected
                );
            }
        }
    }

    #[test]
    fn test_hp_fractions_sum() {
        // Проверка: суммы долей соответствуют ожидаемым
        // (не 100%, так как зоны считаются независимо)
        let locations = [
            HitLocationType::RightLeg,
            HitLocationType::LeftLeg,
            HitLocationType::Abdomen,
            HitLocationType::Chest,
            HitLocationType::RightArm,
            HitLocationType::LeftArm,
            HitLocationType::Head,
        ];

        let fractions: f32 = locations.iter().map(|l| l.hp_fraction()).sum();

        // Ожидаемая сумма: 2*(1/3) + 1/3 + 4/10 + 2*(1/4) = 2.533...
        assert!((fractions - 2.5333).abs() < 0.001);
    }

    #[test]
    fn test_calculate_location_hp_rounding() {
        // Тест округления вверх для разных значений
        let test_cases = [
            (3, HitLocationType::RightArm, 1), // 3 * 0.25 = 0.75 → ceil = 1
            (4, HitLocationType::RightArm, 1), // 4 * 0.25 = 1.0 → ceil = 1
            (5, HitLocationType::RightArm, 2), // 5 * 0.25 = 1.25 → ceil = 2
            (10, HitLocationType::Head, 4),    // 10 * 0.333 = 3.33 → ceil = 4
            (12, HitLocationType::Chest, 5),   // 12 * 0.4 = 4.8 → ceil = 5
        ];

        for (total, location, expected) in test_cases {
            let result = calculate_location_hp(total, location);
            assert_eq!(
                result, expected,
                "HP for {:?} with total {} should be {}",
                location, total, expected
            );
        }
    }

    #[test]
    fn test_is_critical() {
        assert!(!is_critical(HitLocationType::RightArm));
        assert!(!is_critical(HitLocationType::LeftLeg));
        assert!(!is_critical(HitLocationType::Abdomen)); // Не критична по базовым правилам
        assert!(is_critical(HitLocationType::Chest));
        assert!(is_critical(HitLocationType::Head));
    }

    #[test]
    fn test_iter_by_criticality_order() {
        let order: Vec<_> = iter_by_criticality().collect();

        // Проверка: голова последняя (наиболее критична)
        assert_eq!(order.last(), Some(&HitLocationType::Head));

        // Проверка: руки первые (наименее критичны)
        assert!(matches!(
            order[0],
            HitLocationType::RightArm | HitLocationType::LeftArm
        ));

        // Проверка: все 7 зон присутствуют
        assert_eq!(order.len(), 7);
    }

    #[test]
    fn test_serialize_deserialize() {
        // Тест сериализации через serde
        let location = HitLocationType::Chest;
        let json = serde_json::to_string(&location).unwrap();
        assert_eq!(json, "\"Chest\""); // PascalCase благодаря #[serde(rename_all)]

        let parsed: HitLocationType = serde_json::from_str("\"Head\"").unwrap();
        assert_eq!(parsed, HitLocationType::Head);
    }
}
