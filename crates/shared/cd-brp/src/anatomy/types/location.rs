/// Возвращает итератор по всем зонам в порядке возрастания "критичности".
///
/// # Назначение
/// Полезно для:
/// - Последовательной проверки смерти (сначала критические зоны)
/// - Отладки: вывод состояния анатомии в читаемом порядке
/// - Сериализации: детерминированный порядок полей
///
/// # Порядок зон (от наименее к наиболее критичным)
/// ```text
/// 1. Руки (манипуляции, не смертельно)
/// 2. Ноги (передвижение, не смертельно)
/// 3. Живот (органы, риск кровотечения)
/// 4. Грудь (жизненно важные органы)
/// 5. Голова (мозг, мгновенная смерть)
/// ```
///
/// # Пример использования
/// ```rust,ignore
/// // Проверка смерти: сначала критические зоны
/// for location in HitLocationType::iter_by_criticality() {
///     if matches!(location, Head | Chest | Abdomen) {
///         if let Some(part) = anatomy.parts.get(&location) {
///             if part.is_destroyed() {
///                 return false; // Смерть
///             }
///         }
///     }
/// }
/// ```
#[must_use]
pub fn iter_by_criticality() -> impl Iterator<Item = HitLocationType> {
    // Порядок: руки → ноги → живот → грудь → голова
    [
        HitLocationType::RightArm,
        HitLocationType::LeftArm,
        HitLocationType::RightLeg,
        HitLocationType::LeftLeg,
        HitLocationType::Abdomen,
        HitLocationType::Chest,
        HitLocationType::Head,
    ]
    .into_iter()
}

/// Проверяет, является ли зона критической для выживания.
///
/// # Возвращаемое значение
/// - `true`: уничтожение этой зоны = мгновенная смерть (по правилам BRP)
/// - `false`: зона может быть уничтожена без летального исхода
///
/// # Использование
/// ```rust,ignore
/// // В Anatomy::is_alive()
/// if location.is_critical() && part.is_destroyed() {
///     return false; // Смерть
/// }
/// ```
///
/// # Расширение
/// В симулятивных режимах можно учитывать:
/// - Повреждение живота → риск смерти от внутреннего кровотечения
/// - Повреждение шеи (если добавлена) → удушье
#[must_use]
#[inline]
pub fn is_critical(location: HitLocationType) -> bool {
    matches!(location, HitLocationType::Head | HitLocationType::Chest)
}

/// Рассчитывает максимальные ХП для зоны на основе общих ХП персонажа.
///
/// # Параметры
/// - `total_hp`: общие ХП персонажа (обычно `(CON + SIZ) / 2` по BRP)
/// - `location`: зона для расчёта
///
/// # Возвращаемое значение
/// Максимальные ХП зоны, округлённые вверх до целого.
///
/// # Пример
/// ```rust,ignore
/// let total = 12; // Персонаж с 12 общими ХП
/// let head_hp = calculate_location_hp(total, HitLocationType::Head);
/// assert_eq!(head_hp, 4); // 12 * (1/3) = 4.0 → ceil(4.0) = 4
///
/// let arm_hp = calculate_location_hp(total, HitLocationType::RightArm);
/// assert_eq!(arm_hp, 3); // 12 * (1/4) = 3.0 → ceil(3.0) = 3
/// ```
///
/// # Обоснование округления
/// Использование `ceil()` гарантирует:
/// - Минимум 1 ХП для любой зоны (даже у слабых персонажей)
/// - Консистентность с оригинальными правилами BRP
/// - Предсказуемость при балансировке урона
#[must_use]
#[inline]
pub fn calculate_location_hp(total_hp: i32, location: HitLocationType) -> i32 {
    (total_hp as f32 * location.hp_fraction()).ceil() as i32
}

impl std::fmt::Display for HitLocationType {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let name = match self {
            Self::RightLeg => "правая нога",
            Self::LeftLeg => "левая нога",
            Self::Abdomen => "живот",
            Self::Chest => "грудь",
            Self::RightArm => "правая рука",
            Self::LeftArm => "левая рука",
            Self::Head => "голова",
        };
        write!(f, "{}", name)
    }
}

