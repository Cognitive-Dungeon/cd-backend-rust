use serde::{Deserialize, Serialize};

/// Типы травм (Injuries) по правилам BRP/DF.
///
/// Травмы — это персистентные состояния, которые накладываются на часть тела
/// при достижении определённых порогов урона. В отличие от ран (Wound),
/// травмы не заживают автоматически и требуют медицинского вмешательства.
///
/// # Механика
/// - `Bleeding`: Потеря 1 ХП в раунд, пока не остановлено (жгут, бинт, магия)
/// - `Fractured`: Штраф 50% к действиям с этой частью, невозможно бегать/атаковать
/// - `Severed`: Часть уничтожена, функция утрачена безвозвратно (ампутация)
///
/// # Источники
/// - *Basic Roleplaying UGE*, стр. 14-15: "Major Wounds" и последствия
/// - *Dwarf Fortress*: механика `SEVERED` и `FRACTURE`
///
/// # Пример
/// ```
/// // Нога с переломом не позволяет использовать её для движения
/// if leg.injuries.contains(&Injury::Fractured) {
///     action_points /= 2; // Хромает
/// }
/// ```
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum Injury {
    /// Кровотечение: часть теряет 1 ХП в раунд до остановки.
    ///
    /// # Эффекты
    /// - Пассивная потеря ХП (1/раунд)
    /// - Штраф к концентрации (-10% к навыкам)
    /// - Риск шока при потере >25% крови
    ///
    /// # Лечение
    /// Требует действия "Apply Bandage" или "Tourniquet" (Skill: First Aid).
    /// Без лечения кровотечение может привести к смерти от кровопотери.
    Bleeding,

    /// Перелом: структурное повреждение кости/сустава.
    ///
    /// # Эффекты
    /// - Функция части снижена на 50% (нельзя бегать, атаковать, держать)
    /// - Боль ×2 при использовании части
    /// - Риск усугубления при нагрузке (проверка STR)
    ///
    /// # Лечение
    /// Требует иммобилизации (шина) и времени на срастание (недели).
    /// В полевых условиях: штраф к действиям сохраняется до полноценного лечения.
    ///
    /// # Пример из правил
    /// > "A fractured leg reduces MOV to 1 and prevents running." — BRP UGE, p.15
    Fractured,

    /// Отсечение/уничтожение: часть безвозвратно утрачена.
    ///
    /// # Эффекты
    /// - Функция части = 0 (невозможно использовать)
    /// - Мгновенная кровопотеря (1D3 ХП)
    /// - Шок: проверка POW или потеря сознания
    /// - Постоянный штраф к характеристикам (например, -2 STR за потерю руки)
    ///
    /// # Необратимость
    /// Только магия высокого уровня или кибернетика могут восстановить функцию.
    /// В реалистичных кампаниях: перманентная инвалидность.
    ///
    /// # Пример
    /// ```
    /// // Отсечённая рука не может держать оружие
    /// if arm.injuries.contains(&Injury::Severed) {
    ///     character.equipment.drop_held_items();
    /// }
    /// ```
    Severed,
}

/// Тип урона, определяющий механику проникновения и последствия.
///
/// Используется в системе симуляции анатомии для расчёта:
/// - Глубины проникновения через ткани
/// - Вероятности специфических травм (перелом, ожог, разрыв)
/// - Эффективности брони против данного типа
///
/// # Классификация по источнику
/// | Тип | Примеры оружия | Особенность механики |
/// |-----|---------------|---------------------|
/// | `Blunt` | Дубина, кулак, падение | Урон по площади, риск перелома |
/// | `Cutting` | Меч, топор, стекло | Кровотечение, риск отсечения |
/// | `Piercing` | Копьё, стрела, нож | Глубокое проникновение, урон органам |
/// | `Burning` | Огонь, кислота, лазер | Игнор части брони, некроз тканей |
/// | `Tearing` | Когти, взрыв, разрыв | Множественные раны, высокий болевой шок |
/// | `Crushing` | Молот, камень, давление | Структурные повреждения, оглушение |
///
/// # Взаимодействие с бронёй
/// ```rust,ignore
/// // Пример расчёта эффективности брони
/// let effective_armor = match (armor_type, wound_type) {
///     (Armor::Chainmail, WoundType::Piercing) => armor_value / 2, // Кольчуга слаба против колющего
///     (Armor::Plate, WoundType::Cutting) => armor_value * 2,     // Латы сильны против режущего
///     _ => armor_value,
/// };
/// ```
///
/// # Ссылки
/// - *BRP UGE*, стр. 149: "Weapon Special Effects"
/// - *Dwarf Fortress*: механика `ATTACK_TYPE` и взаимодействие с материалами
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum WoundType {
    /// Тупой урон: дробящее воздействие без проникновения.
    ///
    /// # Механика
    /// - Урон распределяется по площади (меньше глубина, больше тканей затронуто)
    /// - Высокий шанс `Fractured` при уроне >50% от макс. ХП части
    /// - Эффект "Stun": проверка CON или потеря действия
    ///
    /// # Примеры источников
    /// - Оружие: молот, булава, кистень
    /// - Окружение: падение с высоты, удар камнем
    /// - Магия: заклинания силы (Force Bolt)
    Blunt,

    /// Режущий урон: острое лезвие, разрезающее ткани.
    ///
    /// # Механика
    /// - Высокий шанс `Bleeding` (50% при попадании)
    /// - Риск `Severed` при уроне ≥2× макс. ХП части (ампутация)
    /// - Игнорирует 25% мягкой брони (кожа, ткань)
    ///
    /// # Тактическое применение
    /// Эффективно против незащищённых целей, слабо против лат.
    /// Специальный эффект "Bleeding" требует немедленного лечения.
    ///
    /// # Примеры источников
    /// - Оружие: меч, топор, серп, осколки стекла
    Cutting,

    /// Колющий урон: проникновение остриём вглубь тела.
    ///
    /// # Механика
    /// - Максимальная глубина проникновения (риск повреждения органов)
    /// - Игнорирует 50% брони, если остриё уже (tip_size < 5mm)
    /// - Высокий шанс внутреннего кровотечения (скрытый урон)
    ///
    /// # Особые правила
    /// - При попадании в грудную клетку: проверка на повреждение лёгких/сердца
    /// - При попадании в голову: мгновенная смерть при уроне ≥ макс. ХП
    ///
    /// # Примеры источников
    /// - Оружие: копьё, рапира, стрела, кинжал
    /// - Природное: клыки, рога, шипы
    Piercing,

    /// Термический/химический урон: ожог, обморожение, коррозия.
    ///
    /// # Механика
    /// - Игнорирует металлическую броню (теплопроводность)
    /// - Накладывает состояние `Necrotic` (ткань отмирает, не заживает)
    /// - Продолжающийся урон: 1 ХП/раунд в течение 1D3 раундов
    ///
    /// # Лечение
    /// Требует специализированных средств (мази, магия исцеления).
    /// Обычные бинты неэффективны против ожогов.
    ///
    /// # Примеры источников
    /// - Огонь: факел, огненный шар, драконье дыхание
    /// - Холод: ледяное заклинание, арктическая среда
    /// - Химия: кислота, щёлочь, ядовитый газ
    Burning,

    /// Рваный урон: разрыв тканей силой, а не режущей кромкой.
    ///
    /// # Механика
    /// - Множественные мелкие раны вместо одной глубокой
    /// - Высокий болевой шок: проверка POW или потеря сознания
    /// - Сложно наложить жгут (множественные источники кровотечения)
    ///
    /// # Особые эффекты
    /// - При уроне ≥75% макс. ХП: автоматический `Fractured` + `Bleeding`
    /// - Шанс заражения ×2 (разорванные ткани хуже заживают)
    ///
    /// # Примеры источников
    /// - Природное: когти зверя, пасть хищника
    /// - Взрывное: граната, динамит, магический взрыв
    /// - Механическое: ловушки, механизмы, промышленное оборудование
    Tearing,

    /// Давящий урон: экстремальное сжатие или размозжение.
    ///
    /// # Механика
    /// - Структурное разрушение: автоматический `Broken` при уроне >30% макс. ХП
    /// - Игнорирует броню при уроне ≥10 (давление проходит сквозь)
    /// - Эффект "Crush": проверка STR или часть становится `Useless`
    ///
    /// # Критические последствия
    /// - Грудная клетка: проверка CON или удушье (потеря 2 ХП/раунд)
    /// - Конечности: автоматическая ампутация при уроне ≥3× макс. ХП
    /// - Голова: мгновенная смерть
    ///
    /// # Примеры источников
    /// - Окружение: обвал, тиски, гидравлический пресс
    /// - Оружие: молот великана, заклинание "Crushing Hand"
    /// - Существа: хватка гигантского змея, давление глубины
    Crushing,
}

/// Степень тяжести раны, определяющая функциональные последствия.
///
/// Используется для градации влияния ран на геймплей:
/// - Расчёт штрафов к характеристикам и навыкам
/// - Определение необходимости лечения
/// - Триггеры для системных событий (шок, потеря сознания)
///
/// # Шкала тяжести (по возрастанию)
/// ```
/// None < Minor < Inhibited < FunctionLoss < Broken < Missing
/// ```
///
/// # Взаимосвязь с другими системами
/// - `ActionPoints`: `Inhibited` = -50% AP, `FunctionLoss` = 0 AP для части
/// - `Movement`: `Broken` нога = скорость 1, `Missing` нога = невозможно ходить
/// - `Pain`: каждый уровень добавляет +25 к уровню боли (макс. 200 = потеря сознания)
///
/// # Пример расчёта штрафа к навыку
/// ```rust,ignore
/// let penalty = match wound.severity {
///     WoundSeverity::None => 0,
///     WoundSeverity::Minor => -5,
///     WoundSeverity::Inhibited => -25,
///     WoundSeverity::FunctionLoss => -50,
///     WoundSeverity::Broken | WoundSeverity::Missing => -100,
/// };
/// skill_chance = (base_chance + penalty).clamp(1, 200);
/// ```
///
/// # Ссылки
/// - *Dwarf Fortress*: уровни ран `MINOR_DAMAGED` → `FUNCTION_LOSS` → `MISSING` [[8]]
/// - *BRP UGE*: "Major Wounds" и их последствия (стр. 14-15)
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
pub enum WoundSeverity {
    /// Отсутствие раны или поверхностное повреждение без последствий.
    ///
    /// # Механика
    /// - Нет штрафов к характеристикам или действиям
    /// - Заживает автоматически за 1-2 раунда
    /// - Не требует лечения (косметический эффект)
    ///
    /// # Примеры
    /// - Царапина от куста
    /// - Лёгкий ушиб, не влияющий на подвижность
    /// - Поверхностный ожог первой степени
    None,

    /// Незначительная рана: боль и минимальный штраф.
    ///
    /// # Механика
    /// - Штраф -5% к навыкам, использующим поражённую часть
    /// - Боль +10 (влияет на концентрацию)
    /// - Заживает за 1 день без лечения, 1 раунд с лечением
    ///
    /// # Геймплейные эффекты
    /// - Анимация "лёгкой хромоты" или "прихрамывания"
    /// - Звуковой эффект боли при использовании части
    /// - Возможность игнорировать штраф ценой доп. усталости
    ///
    /// # Примеры
    /// - Порез, требующий пластыря
    /// - Ушиб мышцы после удара
    /// - Ожог второй степени на небольшом участке
    Minor,

    /// Рана, ограничивающая функцию: значительный штраф к действиям.
    ///
    /// # Механика
    /// - Штраф -50% к навыкам и действиям с поражённой частью
    /// - Боль +25, риск потери концентрации (проверка POW)
    /// - Требует лечения: без него ухудшается до `FunctionLoss` за 1 час
    ///
    /// # Особые правила
    /// - Нельзя выполнять сложные действия (прицельная стрельба, тонкая работа)
    /// - Движение со скоростью 50% от нормы, если затронута нога
    /// - Риск кровотечения (25% шанс `Bleeding` при нагрузке)
    ///
    /// # Примеры
    /// - Глубокий порез мышцы
    /// - Трещина в кости (не полный перелом)
    /// - Ожог, ограничивающий подвижность сустава
    Inhibited,

    /// Потеря функции: часть не может выполнять свою основную задачу.
    ///
    /// # Механика
    /// - Штраф -100% к навыкам, требующим поражённую часть
    /// - Боль +50, автоматическая проверка на шок при получении
    /// - Требует срочного лечения: без него риск смерти/инфекции
    ///
    /// # Последствия по частям тела
    /// | Часть | Эффект потери функции |
    /// |-------|----------------------|
    /// | Рука | Невозможно держать оружие/предметы |
    /// | Нога | Невозможно бегать, штраф к ходьбе |
    /// | Голова | Штраф к восприятию, риск потери сознания |
    /// | Торс | Штраф к выносливости, риск внутренних повреждений |
    ///
    /// # Примеры
    /// - Разрыв сухожилия
    /// - Перелом со смещением
    /// - Глубокий ожог с повреждением нервов
    FunctionLoss,

    /// Структурное разрушение: кость сломана, орган повреждён критически.
    ///
    /// # Механика
    /// - Часть полностью нефункциональна (как `Missing`, но анатомически присутствует)
    /// - Боль +75, автоматическая потеря сознания при получении (проверка POW)
    /// - Риск смерти: 10% за раунд без лечения (кровопотеря/шок)
    ///
    /// # Лечение
    /// Требует хирургического вмешательства (навык: Surgery, сложность: Hard).
    /// Без лечения: часть становится `Missing` за 1 день (некроз/гангрена).
    ///
    /// # Примеры
    /// - Открытый перелом с осколками
    /// - Разрыв внутреннего органа
    /// - Обширный ожог третьей степени с некрозом
    Broken,

    /// Отсутствие части: ампутация, полное уничтожение.
    ///
    /// # Механика
    /// - Функция части = 0, невозможно восстановить без магии/кибернетики
    /// - Мгновенная кровопотеря: 1D6 ХП + проверка на шок
    /// - Постоянный штраф к характеристикам (например, -2 STR за руку)
    ///
    /// # Долгосрочные последствия
    /// - Необходимость протеза/магической замены для восстановления функции
    /// - Психологическая травма: штраф к POW/харизме в социальных взаимодействиях
    /// - Риск фантомных болей (периодические проверки на боль)
    ///
    /// # Примеры
    /// - Отсечённая конечность
    /// - Раздавленная голова
    /// - Выжженное дотла лёгкое
    ///
    /// # Важное замечание
    /// В реалистичных кампаниях `Missing` — перманентное состояние.
    /// В героических/фэнтези: может быть излечено магией уровня `Regenerate`.
    Missing,
}
