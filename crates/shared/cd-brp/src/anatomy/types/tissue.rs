/// Категории биологических тканей по функциональному назначению.
///
/// Используется для:
/// - Определения порядка слоёв при расчёте проникновения урона
/// - Расчёта специфичных эффектов повреждения (кровотечение, паралич, перелом)
/// - Подбора методов лечения и скорости регенерации
///
/// # Порядок проникновения (от внешних к внутренним)
/// ```text
/// 1. Skin        — внешний барьер, минимальная защита
/// 2. Fat         — амортизация, теплоизоляция
/// 3. Muscle      — двигательная функция, основное "мясо"
/// 4. Tendon      — передача усилия от мышцы к кости
/// 5. Ligament    — стабилизация суставов
/// 6. Bone        — структурная опора, защита органов
/// 7. Nerve       — передача сигналов (боль, движение)
/// 8. Artery      — артериальная кровь (высокое давление)
/// 9. Vein        — венозная кровь (низкое давление)
/// 10. OrganTissue — паренхима внутренних органов
/// ```
///
/// # Взаимодействие с типами урона
/// | Ткань | Blunt | Cutting | Piercing | Burning | Особенности |
/// |-------|-------|---------|----------|---------|-------------|
/// | `Skin` | Ушиб | Порез, кровотечение | Прокол | Ожог, некроз | Первый барьер, боль ×1 |
/// | `Fat` | Амортизация | Глубокий порез | Проникновение | Плавление | Снижает урон на 10-20% |
/// | `Muscle` | Разрыв | Кровотечение ×2 | Глубокое повреждение | Обугливание | Боль ×3, функция ↓ |
/// | `Tendon` | Растяжение | Разрыв | Повреждение | Усадка | Потеря функции конечности |
/// | `Ligament` | Вывих | Разрыв | Повреждение | — | Нестабильность сустава |
/// | `Bone` | Перелом | Раскол | Оскольчатый перелом | Кальцинация | Боль ×5, структурный урон |
/// | `Nerve` | Сотрясение | Разрыв | Повреждение | — | Паралич, фантомная боль |
/// | `Artery` | Разрыв | Рассечение | Прокол | — | Кровотечение ×5, риск смерти |
/// | `Vein` | Разрыв | Рассечение | Прокол | — | Кровотечение ×2, медленная потеря |
/// | `Organ` | Ушиб | Разрез | Проникновение | Некроз | Функция органа ↓, системные эффекты |
///
/// # Ссылки
/// - *BRP UGE*, стр. 14: распределение ХП по зонам тела
/// - *Dwarf Fortress*: `TISSUE` с тегами `RELATIVE_THICKNESS`, `PAIN_RECEPTORS`
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum TissueType {
    /// Кожа: внешний защитный слой организма.
    ///
    /// # Механика
    /// - **Толщина**: 1-3 мм (зависит от локации)
    /// - **Боль**: базовый множитель ×1.0
    /// - **Кровотечение**: минимальное (капилляры)
    /// - **Защита**: игнорирует 1-2 урона от тупых атак
    ///
    /// # Особые правила
    /// - При полном уничтожении: риск инфекции ×2 (открытая рана)
    /// - Ожоги кожи: накладывают состояние `Necrosis` при тяжёлых повреждениях
    /// - Заживление: 0.1-0.3 целостности/день без лечения
    ///
    /// # Примеры локаций с разной толщиной
    /// | Локация | Толщина (мм) | Комментарий |
    /// |---------|-------------|-------------|
    /// | Ладонь/подошва | 3-4 | Утолщённая кожа |
    /// | Лицо/шея | 1-2 | Тонкая, чувствительная |
    /// | Спина/грудь | 2-3 | Средняя защита |
    ///
    /// # Взаимодействие с бронёй
    /// Кожаная броня добавляется **поверх** этого слоя, не заменяя его.
    Skin,

    /// Жировая ткань: амортизация и энергозапас.
    ///
    /// # Механика
    /// - **Толщина**: 5-20 мм (зависит от телосложения)
    /// - **Амортизация**: снижает тупой урон на 10-20%
    /// - **Теплоизоляция**: замедляет эффекты `Burning` (холод/жара)
    /// - **Кровотечение**: умеренное (сосуды в жировой прослойке)
    ///
    /// # Особые правила
    /// - Истощение: при голодании толщина уменьшается, снижая защиту
    /// - Ожирение: толщина >15 мм даёт бонус к амортизации, но штраф к подвижности
    /// - Заживление: медленное (0.05-0.1/день), требует калорий
    ///
    /// # Примеры
    /// - Удар дубиной: жир поглощает часть энергии, снижая урон по мышцам
    /// - Глубокий порез: проходит через жир, достигая мышц с уменьшенной силой
    Fat,

    /// Мышечная ткань: двигательная функция и масса тела.
    ///
    /// # Механика
    /// - **Толщина**: 10-30 мм (зависит от развитости и локации)
    /// - **Боль**: множитель ×3.0 (высокая иннервация)
    /// - **Кровотечение**: значительное (0.5-2.0 мл/сек при повреждении)
    /// - **Функция**: повреждение снижает силу/подвижность конечности
    ///
    /// # Особые правила
    /// - При повреждении >50%: штраф -50% к действиям с этой частью
    /// - При повреждении >90%: функция утрачена (`FunctionLoss`)
    /// - Разрыв мышцы: автоматический `Bleeding` + `Inhibited`
    ///
    /// # Лечение и регенерация
    /// - Покой: +0.1-0.2 целостности/день
    /// - Физиотерапия: +0.3-0.5/день (требует навыка **Medicine**)
    /// - Магия/технологии: мгновенное восстановление (фэнтези/киберпанк)
    ///
    /// # Пример из правил
    /// > "A torn muscle reduces the effectiveness of the limb by half until healed."
    /// — Адаптировано из BRP для симулятивной модели
    Muscle,

    /// Сухожилия: передача усилия от мышцы к кости.
    ///
    /// # Механика
    /// - **Толщина**: 2-5 мм (компактная структура)
    /// - **Прочность**: высокая, но хрупкость при резких нагрузках
    /// - **Боль**: множитель ×4.0 (критические нервные окончания)
    /// - **Функция**: разрыв = полная потеря функции конечности
    ///
    /// # Особые правила
    /// - Растяжение (урон 30-60%): штраф -30% к силе, боль ×2
    /// - Разрыв (урон >60%): `FunctionLoss`, требуется хирургия
    /// - Заживление: очень медленное (0.02-0.05/день), риск повторного разрыва
    ///
    /// # Тактическое значение
    /// Целенаправленные атаки на сухожилия (например, "Hamstring")
    /// могут обездвижить противника без летального исхода.
    ///
    /// # Примеры источников повреждения
    /// - Режущее оружие: низкий шанс, но критичные последствия
    /// - Чрезмерная нагрузка: проверка STR или разрыв при рывке
    /// - Ожоги: усадка сухожилий = необратимая контрактура
    Tendon,

    /// Связки: стабилизация суставов и ограничение амплитуды.
    ///
    /// # Механика
    /// - **Толщина**: 1-4 мм (варьируется по суставу)
    /// - **Эластичность**: выдерживает растяжение до 120% длины
    /// - **Боль**: множитель ×3.5 (болевые рецепторы в капсуле сустава)
    /// - **Функция**: повреждение = нестабильность, риск вывиха
    ///
    /// # Особые правила
    /// - Растяжение (урон 20-50%): штраф -20% к точности действий
    /// - Разрыв (урон >50%): вывих при нагрузке, `Inhibited` статус
    /// - Заживление: 0.03-0.08/день, требует иммобилизации
    ///
    /// # Взаимодействие с другими тканями
    /// Повреждение связок часто сопровождается:
    /// - Ушибом кости (контакная нагрузка)
    /// - Растяжением сухожилий (компенсаторная перегрузка)
    /// - Воспалением сустава (системный ответ)
    ///
    /// # Примеры
    /// - Подворот ноги: проверка на разрыв связок голеностопа
    /// - Бросок через плечо: риск разрыва плечевых связок
    Ligament,

    /// Костная ткань: структурная опора и защита органов.
    ///
    /// # Механика
    /// - **Толщина**: 5-15 мм (кортикальный слой)
    /// - **Прочность**: очень высокая, но хрупкость при точечном ударе
    /// - **Боль**: множитель ×5.0 (надкостница богата рецепторами)
    /// - **Кровотечение**: минимальное (кость аваскулярна), но риск повреждения сосудов
    ///
    /// # Особые правила
    /// - Трещина (урон 30-60%): `Broken` статус, боль ×3, функция ↓
    /// - Перелом (урон >60%): `FunctionLoss`, риск повреждения окружающих тканей
    /// - Оскольчатый перелом: автоматическое повреждение `Muscle`/`Nerve` рядом
    ///
    /// # Лечение
    /// - Иммобилизация: предотвращает смещение, +0.05/день заживления
    /// - Репозиция: навык **Medicine** (Hard) для сложных переломов
    /// - Срастание: 2-8 недель игрового времени в зависимости от кости
    ///
    /// # Примеры из правил
    /// > "A fractured bone requires immobilization and reduces limb function to zero until healed."
    /// — BRP UGE, адаптировано для симуляции
    ///
    /// # Особые локации
    /// | Кость | Особенность | Критичность |
    /// |-------|-------------|-------------|
    /// | Череп | Защита мозга | Смертельно при пробитии |
    /// | Рёбра | Защита органов | Риск пневмоторакса при переломе |
    /// | Позвоночник | Нервный центр | Паралич при повреждении |
    /// | Конечности | Движение | Потеря функции при переломе |
    Bone,

    /// Нервная ткань: передача сигналов боли и управления.
    ///
    /// # Механика
    /// - **Толщина**: 0.5-3 мм (зависит от типа нерва)
    /// - **Боль**: множитель ×10.0 (прямая стимуляция рецепторов)
    /// - **Функция**: повреждение = паралич/потеря чувствительности
    /// - **Кровотечение**: отсутствует (нервы аваскулярны)
    ///
    /// # Типы нервов и эффекты повреждения
    /// | Тип | Функция | Эффект повреждения |
    /// |-----|---------|-------------------|
    /// | Сенсорный | Передача боли, осязания | Гипералгезия или анестезия |
    /// | Моторный | Управление мышцами | Паралич, слабость |
    /// | Автономный | Вегетативные функции | Нарушение сердцебиения, дыхания |
    ///
    /// # Особые правила
    /// - Ушиб (урон 10-40%): временное онемение, штраф -20% к точности
    /// - Разрыв (урон >40%): постоянная потеря функции, `FunctionLoss`
    /// - Регенерация: крайне медленная (0.01/день), часто необратима
    ///
    /// # Фантомная боль
    /// При ампутации (`Missing`) повреждённые нервы могут вызывать
    /// периодические приступы боли (проверка POW каждый игровой день).
    ///
    /// # Пример
    /// ```rust,ignore
    /// // Повреждение моторного нерва = паралич руки
    /// if nerve.tissue_type == TissueType::Nerve && nerve.integrity < 0.6 {
    ///     body_part.is_useless = true;
    /// }
    /// ```
    Nerve,

    /// Артерии: сосуды высокого давления, несущие кислородную кровь.
    ///
    /// # Механика
    /// - **Толщина**: 1-4 мм (стенка сосуда)
    /// - **Давление**: высокое (80-120 мм рт.ст.), быстрая кровопотеря
    /// - **Кровотечение**: ×5.0 к базовой скорости при разрыве
    /// - **Боль**: множитель ×2.0 (но основной риск — потеря крови)
    ///
    /// # Особые правила
    /// - Разрыв: автоматический `Bleeding` с высокой скоростью
    /// - Сдавление: временная ишемия тканей ниже по току
    /// - Заживление: требует хирургического шва или магии
    ///
    /// # Критические артерии
    /// | Артерия | Локация | Последствия разрыва |
    /// |---------|---------|---------------------|
    /// | Сонная | Шея | Потеря сознания за 10-15 сек, смерть за 2-3 мин |
    /// | Бедренная | Нога | Кровопотеря 500+ мл/мин, шок за 5 мин |
    /// | Плечевая | Рука | Кровопотеря 200+ мл/мин, потеря функции руки |
    /// | Аорта | Грудь/живот | Мгновенная смерть при полном разрыве |
    ///
    /// # Первая помощь
    /// - Жгут: останавливает кровотечение, но риск некроза через 2 часа
    /// - Давящая повязка: снижает потерю на 50-80%
    /// - Хирургия: единственный способ полного восстановления
    Artery,

    /// Вены: сосуды низкого давления, возвращающие кровь к сердцу.
    ///
    /// # Механика
    /// - **Толщина**: 0.5-2 мм (тоньше артерий)
    /// - **Давление**: низкое (5-10 мм рт.ст.), медленная кровопотеря
    /// - **Кровотечение**: ×2.0 к базовой скорости при разрыве
    /// - **Боль**: множитель ×1.5
    ///
    /// # Особые правила
    /// - Разрыв: `Bleeding`, но легче контролировать, чем артериальный
    /// - Тромбоз: риск при повреждении + иммобилизации (системный эффект)
    /// - Заживление: быстрее артерий (0.1-0.3/день с лечением)
    ///
    /// # Тактическое значение
    /// Венозное кровотечение менее опасно, но:
    /// - Может маскировать серьёзные повреждения
    /// - Создаёт "кровавый след" для отслеживания в стелс-ситуациях
    /// - При множественных повреждениях суммируется в опасную потерю
    ///
    /// # Пример расчёта кровопотери
    /// ```rust,ignore
    /// let bleed_rate = match tissue_type {
    ///     TissueType::Artery => base_damage * 5.0,
    ///     TissueType::Vein => base_damage * 2.0,
    ///     _ => base_damage * 0.5,
    /// };
    /// anatomy.substances.blood_loss_rate += bleed_rate;
    /// ```
    Vein,

    /// Паренхима органов: функциональная ткань внутренних органов.
    ///
    /// # Механика
    /// - **Толщина**: варьируется (5-50 мм в зависимости от органа)
    /// - **Функция**: специфична для каждого органа (см. `OrganType`)
    /// - **Боль**: множитель ×4.0 (висцеральная боль, плохо локализуемая)
    /// - **Кровотечение**: высокое (органы хорошо васкуляризированы)
    ///
    /// # Особые правила
    /// - Ушиб (урон 20-50%): временное снижение функции органа
    /// - Разрыв (урон >50%): `Ruptured`, риск внутреннего кровотечения
    /// - Некроз (урон >80%): `Necrotic`, функция = 0, риск сепсиса
    ///
    /// # Органоспецифичные эффекты
    /// | Орган | Функция | Эффект повреждения |
    /// |-------|---------|-------------------|
    /// | Печень | Детоксикация | Накопление токсинов, риск комы |
    /// | Почки | Фильтрация | Уремия, отёки, нарушение электролитов |
    /// | Лёгкие | Газообмен | Гипоксия, одышка, риск пневмонии |
    /// | Сердце | Кровообращение | Аритмия, шок, смерть при остановке |
    /// | Мозг | Контроль | Спутанность, паралич, смерть при критическом повреждении |
    ///
    /// # Лечение
    /// Требует специализированного вмешательства:
    /// - Хирургия: восстановление целостности (навык **Surgery**)
    /// - Поддержка: ИВЛ, диализ, инфузии (ресурсы)
    /// - Магия/технологии: регенерация (фэнтези/киберпанк)
    OrganTissue,
}

