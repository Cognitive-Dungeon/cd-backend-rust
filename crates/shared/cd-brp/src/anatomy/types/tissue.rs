#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_default_skin_properties() {
        let skin = TissueLayer::default_skin();
        assert_eq!(skin.tissue_type, TissueType::Skin);
        assert!((skin.thickness - 2.0).abs() < f32::EPSILON);
        assert!((skin.integrity - 1.0).abs() < f32::EPSILON);
        assert!((skin.pain_receptors - 1.0).abs() < f32::EPSILON);
        assert!((skin.bleeding_rate - 0.1).abs() < f32::EPSILON);
    }

    #[test]
    fn test_default_muscle_properties() {
        let muscle = TissueLayer::default_muscle(10);
        assert_eq!(muscle.tissue_type, TissueType::Muscle);
        assert!((muscle.thickness - 10.0).abs() < f32::EPSILON);
        assert!((muscle.pain_receptors - 3.0).abs() < f32::EPSILON);
        assert!((muscle.bleeding_rate - 0.5).abs() < f32::EPSILON);
    }

    #[test]
    fn test_is_destroyed_threshold() {
        let mut tissue = TissueLayer::default_skin();

        // Здоровая ткань
        assert!(!tissue.is_destroyed());

        // На пороге
        tissue.integrity = 0.0;
        assert!(tissue.is_destroyed());

        // Отрицательная целостность (перелеченный урон)
        tissue.integrity = -0.5;
        assert!(tissue.is_destroyed());
    }

    #[test]
    fn test_is_inhibited_range() {
        let mut tissue = TissueLayer::default_skin();

        // Здоровая
        tissue.integrity = 0.7;
        assert!(!tissue.is_inhibited());

        // На границе
        tissue.integrity = 0.5;
        assert!(!tissue.is_inhibited()); // Строго меньше 0.5

        // В диапазоне ограничений
        tissue.integrity = 0.3;
        assert!(tissue.is_inhibited());

        // Уничтоженная
        tissue.integrity = 0.0;
        assert!(!tissue.is_inhibited()); // Отдельное состояние
    }

    #[test]
    fn test_relative_damage_calculation() {
        let mut tissue = TissueLayer::default_skin();

        // Полностью здорова
        assert!((tissue.relative_damage() - 0.0).abs() < f32::EPSILON);

        // Наполовину повреждена
        tissue.integrity = 0.5;
        assert!((tissue.relative_damage() - 0.5).abs() < f32::EPSILON);

        // Почти уничтожена
        tissue.integrity = 0.1;
        assert!((tissue.relative_damage() - 0.9).abs() < f32::EPSILON);

        // Уничтожена
        tissue.integrity = 0.0;
        assert!((tissue.relative_damage() - 1.0).abs() < f32::EPSILON);
    }

    #[test]
    fn test_relative_damage_with_custom_max() {
        let tissue = TissueLayer {
            tissue_type: TissueType::Bone,
            thickness: 10.0,
            integrity: 1.5,     // Абсолютное значение
            max_integrity: 3.0, // Но максимум выше
            pain_receptors: 5.0,
            bleeding_rate: 0.0,
        };

        // Относительное повреждение: 1 - (1.5/3.0) = 0.5
        assert!((tissue.relative_damage() - 0.5).abs() < f32::EPSILON);
    }
}
