//! Система тканей организма для симулятивной анатомии.
//!
//! Этот модуль реализует детализированную модель биологических тканей,
//! вдохновлённую механиками **Dwarf Fortress** и **CDDA**. Каждая ткань
//! имеет уникальные свойства, влияющие на:
//! - Проникновение урона через слои тела
//! - Болевые ощущения и функциональные штрафы
//! - Кровотечение и риск инфицирования
//! - Скорость заживления и регенерации
//!
//! # Архитектура слоёв
//! Ткани упорядочены от внешних к внутренним для расчёта проникновения:
//! ```text
//! Skin → Fat → Muscle → [Bone/Nerve/Artery/Vein] → OrganTissue
//! ```
//!
//! При нанесении урона система последовательно "проходит" через слои,
//! уменьшая проникающую способность атаки на толщину каждой ткани.
//!
//! # Источники
//! - *Basic Roleplaying UGE*, стр. 14-15: "Hit Locations", "Major Wounds"
//! - *Dwarf Fortress*: механика `BODY_DETAIL_PLAN`, `TISSUE_LAYER` [[8]]
//! - *CDDA*: система повреждения тканей, кровотечений, боли
//!
//! # Пример использования
//! ```rust,ignore
//! // Создание слоя кожи с параметрами по умолчанию
//! let skin = TissueLayer::default_skin();
//!
//! // Проверка: уничтожена ли ткань?
//! if skin.is_destroyed() {
//!     // Кожа пробита, урон переходит к следующему слою
//!     apply_damage_to_next_layer(...);
//! }
//!
//! // Расчёт боли от повреждения ткани
//! let pain = tissue.pain_receptors * damage_factor;
//! anatomy.vitals.pain += pain;
//! ```

