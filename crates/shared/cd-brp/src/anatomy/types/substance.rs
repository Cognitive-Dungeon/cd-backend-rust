//! Система веществ, токсинов и инфекций для симулятивной анатомии.
//!
//! Этот модуль реализует физиологические процессы организма:
//! - Кровотечение и гиповолемический шок
//! - Метаболизм токсинов и лекарств
//! - Прогрессия инфекций с иммунным ответом
//! - Гидратация и кислородное насыщение
//!
//! # Архитектура
//! Все данные хранятся в компоненте [`SubstancePool`], который обновляется
//! системами в фиксированном временном шаге (`FixedUpdate`). Это обеспечивает
//! детерминизм для сетевой репликации и воспроизводимости симуляции.
//!
//! # Источники
//! - *Basic Roleplaying UGE*, стр. 14-15: "Major Wounds", кровотечение
//! - *Dwarf Fortress*: механика `SYNDROME`, `CE_BODY_COMPONENT_INTERACTION` [[8]]
//! - *CDDA*: система инфекций, иммунный ответ, метаболизм веществ
//!
//! # Пример использования
//! ```rust,ignore
//! // Добавление токсина при отравленном оружии
//! if weapon.has_poison {
//!     anatomy.substances.toxins.insert(
//!         ToxinType::Venom,
//!         ToxinLevel {
//!             concentration: weapon.poison_strength,
//!             half_life: 2.0, // 2 часа полураспада
//!         }
//!     );
//! }
//!
//! // Проверка на сепсис в системе обновления виталов
//! for infection in anatomy.substances.pathogens.values() {
//!     if infection.symptoms.contains(&InfectionSymptom::SystemicShock(0.8)) {
//!         anatomy.vitals.state = CharacterState::Critical;
//!     }
//! }
//! ```

