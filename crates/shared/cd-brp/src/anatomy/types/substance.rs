/// Категории токсичных веществ по механизму воздействия.
///
/// Используется для:
/// - Расчёта метаболизма (разный `half_life` для разных типов)
/// - Применения специфичных эффектов (`ToxinEffect`)
/// - Определения антидотов и методов лечения
///
/// # Классификация по источнику
/// | Тип | Примеры | Механизм действия | Лечение |
/// |-----|---------|------------------|---------|
/// | `Poison` | Мышьяк, цианид | Блокировка клеточного дыхания | Антидот, детокс |
/// | `Drug` | Морфин, стимуляторы | Влияние на нейромедиаторы | Время, поддержка |
/// | `Alcohol` | Этанол, метанол | Депрессант ЦНС, токсичен для печени | Время, диализ |
/// | `Venom` | Змеиный яд, скорпион | Нейротоксин/гемотоксин, быстрый эффект | Антивенин, иммобилизация |
///
/// # Взаимодействие с системой навыков
/// Навык **First Aid** или **Pharmacy** может снизить концентрацию токсина:
/// ```rust,ignore
/// let reduction = skill_check(first_aid, difficulty) * 0.1;
/// toxin.concentration *= 1.0 - reduction;
/// ```
///
/// # Ссылки
/// - *BRP UGE*, стр. 152: "Poisons and Drugs"
/// - *Dwarf Fortress*: `SYNDROME` с тегами `CE_ADD_SYNDROME_DILUTE`
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum ToxinType {
    /// Общие яды: растительные, минеральные, синтетические.
    ///
    /// # Механика
    /// - Постепенное накопление урона органам (печень, почки)
    /// - Штраф к характеристикам: -1 CON за каждый 10% концентрации
    /// - Риск смерти при концентрации >90%
    ///
    /// # Примеры источников
    /// - Оружие: отравленные клинки, стрелы
    /// - Окружение: загрязнённая вода, ядовитые растения
    /// - Магия: заклинания яда, проклятия
    Poison,

    /// Фармацевтические препараты: легальные и нелегальные.
    ///
    /// # Механика
    /// - Двойной эффект: терапевтический (+) и побочный (-)
    /// - Зависимость: при длительном приёме требуется увеличение дозы
    /// - Синдром отмены: штрафы при резком прекращении
    ///
    /// # Примеры эффектов
    /// | Препарат | Терапевтический эффект | Побочный эффект |
    /// |----------|------------------------|-----------------|
    /// | Морфин | -50% боль, +20% шок | -30% сознание, риск зависимости |
    /// | Стимуляторы | +20% AP, +10% DEX | +25% боль, истощение после |
    /// | Седативные | -40% боль, +30% шок | -50% восприятие, замедление |
    ///
    /// # Лечение
    /// Требует навыка **Pharmacy** для точного дозирования.
    /// Передозировка обрабатывается как отравление `Poison`.
    Drug,

    /// Алкогольные вещества: этанол, метанол, суррогаты.
    ///
    /// # Механика
    /// - Стадии опьянения: 0-30% (лёгкое), 30-60% (среднее), 60-90% (сильное), >90% (кома)
    /// - Штрафы: -5% навыков за каждые 10% концентрации
    /// - Бонусы: -20% боль, +10% харизма (социальные взаимодействия)
    /// - Долгосрочный урон: повреждение печени при хроническом употреблении
    ///
    /// # Особые правила
    /// - Метанол: в 3× токсичнее этанола, риск слепоты (штраф к восприятию)
    /// - Похмелье: после снижения концентрации <10% — временные штрафы
    ///
    /// # Примеры источников
    /// - Предметы: бутылки, зелья, трофеи
    /// - Окружение: таверны, праздники, выживание
    Alcohol,

    /// Биологические яды: змеиный, паучий, скорпионий, насекомые.
    ///
    /// # Механика
    /// - Быстрое действие: эффекты проявляются за 1-3 раунда
    /// - Типы токсинов:
    ///   - *Нейротоксин*: паралич, остановка дыхания
    ///   - *Гемотоксин*: разрушение тканей, кровотечение
    ///   - *Цитотоксин*: некроз, локальное уничтожение тканей
    /// - Шанс аллергической реакции: 10% — анафилактический шок
    ///
    /// # Лечение
    /// Требует специфичного антивенина или навыка **Survival** для первой помощи.
    /// Без лечения: прогрессия симптомов каждые 10 минут игрового времени.
    ///
    /// # Примеры источников
    /// - Существа: змеи, пауки, скорпионы, ядовитые насекомые
    /// - Оружие: ядовитые наконечники, природные токсины
    /// - Магия: заклинания призыва ядовитых существ
    Venom,
}

