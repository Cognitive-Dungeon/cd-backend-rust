/// Концентрация токсина в организме с параметрами метаболизма.
///
/// # Механика метаболизма
/// Концентрация снижается по экспоненциальному закону:
/// ```math
/// C(t) = C₀ × e^(-ln(2) × t / half_life)
/// ```
/// где:
/// - `C₀` — начальная концентрация
/// - `t` — прошедшее время (часы)
/// - `half_life` — период полураспада (часы)
///
/// # Пример расчёта
/// ```rust,ignore
/// // Токсин с half_life = 2.0 часа, начальная концентрация = 100.0
/// // Через 4 часа: концентрация = 100 × (0.5)^(4/2) = 25.0
/// let elapsed_hours = 4.0;
/// let new_concentration = toxin.concentration
///     * (0.5_f32).powf(elapsed_hours / toxin.half_life);
/// ```
///
/// # Взаимодействие с характеристиками
/// - **CON**: снижает эффективный `half_life` на 10% за каждые 5 пунктов выше 10
/// - **POW**: ускоряет детоксикацию через иммунную систему
/// - **EDU**: бонус к эффективности медицинских вмешательств
///
/// # Пороговые эффекты
/// | Концентрация | Эффект |
/// |--------------|--------|
/// | <10% | Бессимптомное носительство |
/// | 10-30% | Лёгкие симптомы, минимальные штрафы |
/// | 30-60% | Умеренные симптомы, требуют лечения |
/// | 60-90% | Тяжёлые симптомы, риск смерти |
/// | >90% | Критическое состояние, немедленная помощь |
///
/// # Ссылки
/// - *BRP UGE*, стр. 152: "Poison Mechanics"
/// - Фармакокинетика: модель однокамерного распределения
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ToxinLevel {
    /// Текущая концентрация токсина в условных единицах (0.0-100.0).
    ///
    /// Значение используется для:
    /// - Расчёта штрафов к характеристикам и навыкам
    /// - Определения необходимости лечения
    /// - Триггеров системных событий (потеря сознания, смерть)
    ///
    /// # Обновление
    /// Концентрация обновляется в системе `healing_tick_system`
    /// на основе `half_life` и характеристик персонажа.
    pub concentration: f32,

    /// Период полураспада токсина в игровых часах.
    ///
    /// Определяет скорость естественной детоксикации:
    /// - Короткий (0.5-2.0): быстро выводится, но может быть очень токсичным
    /// - Средний (2.0-12.0): баланс между опасностью и лечением
    /// - Длинный (12.0+): хроническое отравление, требует длительного лечения
    ///
    /// # Модификаторы
    /// - **CON**: снижает эффективный half_life на 10% за каждые 5 пунктов выше 10
    /// - **Печень**: повреждение органа увеличивает half_life ×1.5-2.0
    /// - **Лечение**: медицинские вмешательства могут искусственно снизить half_life
    ///
    /// # Примеры значений
    /// | Токсин | half_life (часы) | Комментарий |
    /// |--------|-----------------|-------------|
    /// | Этанол | 0.5-1.0 | Быстро метаболизируется |
    /// | Морфин | 2.0-4.0 | Требует мониторинга |
    /// | Мышьяк | 24.0+ | Хроническое накопление |
    /// | Нейротоксин | 0.1-0.5 | Мгновенное действие, быстрое выведение |
    pub half_life: f32,
}

