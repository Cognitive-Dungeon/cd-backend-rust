/// Категории патогенов по биологической классификации.
///
/// Используется для:
/// - Определения скорости репликации (`virulence`)
/// - Расчёта иммунного ответа организма
/// - Подбора специфичного лечения (антибиотики, антивирусы)
///
/// # Сравнительная таблица патогенов
/// | Тип | Скорость репликации | Уязвимость к лечению | Особые риски |
/// |-----|---------------------|---------------------|--------------|
/// | `Bacteria` | Средняя | Высокая (антибиотики) | Сепсис, абсцессы |
/// | `Virus` | Высокая | Низкая (поддерживающая терапия) | Системное поражение, мутации |
/// | `Fungus` | Низкая | Средняя (противогрибковые) | Некроз тканей, хронизация |
/// | `Parasite` | Очень низкая | Зависит от вида | Анемия, повреждение органов |
///
/// # Взаимодействие с иммунной системой
/// Иммунный ответ рассчитывается как:
/// ```rust,ignore
/// let immune_response = (CON + POW) / 2 + medical_bonus;
/// let clearance_rate = immune_response * pathogen.virulence;
/// infection.incubation_remaining -= clearance_rate * delta_hours;
/// ```
///
/// # Ссылки
/// - *BRP UGE*, стр. 153: "Diseases and Healing"
/// - *Dwarf Fortress*: `SYNDROME` с тегами `CE_BODY_MAT_INTERACTION`
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum PathogenId {
    /// Бактериальные инфекции: стафилококк, стрептококк, клостридии.
    ///
    /// # Механика
    /// - Инкубационный период: 1-24 часа игрового времени
    /// - Симптомы: лихорадка (+1-3°С), воспаление, гнойные выделения
    /// - Риск сепсиса: 20% при отсутствии лечения >48 часов
    ///
    /// # Лечение
    /// - Антибиотики: снижают `virulence` на 50-90%
    /// - Хирургия: удаление абсцессов, дренирование
    /// - Иммунитет: естественная выработка антител после излечения
    ///
    /// # Примеры источников
    /// - Окружение: грязная вода, разлагающиеся тела, антисанитария
    /// - Ранения: загрязнённые раны, укусы животных
    /// - Магия: проклятия гнили, некромантия
    Bacteria,

    /// Вирусные инфекции: грипп, бешенство, гипотетические патогены.
    ///
    /// # Механика
    /// - Быстрое распространение: инкубация 30 мин - 6 часов
    /// - Системные симптомы: высокая лихорадка, слабость, спутанность сознания
    /// - Риск хронизации: 10% — переход в персистирующую форму
    ///
    /// # Особые правила
    /// - Вирусы не лечатся антибиотиками (требуется специфичная терапия)
    /// - Высокая контагиозность: риск передачи другим персонажам
    /// - Мутационный потенциал: в фэнтези-сеттингах — риск трансформации
    ///
    /// # Примеры источников
    /// - Существа: укусы инфицированных животных, летучих мышей
    /// - Окружение: эпидемии, заражённые зоны, лаборатории
    /// - Магия: вирусные заклинания, биологическое оружие
    Virus,

    /// Грибковые инфекции: кандидоз, аспергиллёз, мукормикоз.
    ///
    /// # Механика
    /// - Медленное развитие: инкубация 1-7 дней
    /// - Локальные симптомы: некроз тканей, изменение цвета кожи/слизистых
    /// - Риск системного поражения: 5% при иммунодефиците
    ///
    /// # Лечение
    /// - Противогрибковые препараты: требуют длительного курса
    /// - Хирургическая санация: удаление некротизированных тканей
    /// - Укрепление иммунитета: критично для предотвращения рецидивов
    ///
    /// # Примеры источников
    /// - Окружение: сырые пещеры, разлагающаяся органика, плесень
    /// - Ранения: загрязнение почвы в глубоких ранах
    /// - Магия: заклинания гнили, проклятия разложения
    Fungus,

    /// Паразитарные инвазии: гельминты, простейшие, эктопаразиты.
    ///
    /// # Механика
    /// - Хроническое течение: симптомы проявляются неделями/месяцами
    /// - Системные эффекты: анемия (-10% к физическим характеристикам), истощение
    /// - Локальные повреждения: в зависимости от локализации паразита
    ///
    /// # Особые правила
    /// - Некоторые паразиты могут быть полезны (симбиоз) — требует проверки
    /// - Риск передачи: через воду, пищу, контакт с инфицированными
    /// - Диагностика: требует навыка **Medicine** или **Survival**
    ///
    /// # Примеры источников
    /// - Окружение: загрязнённая вода, сырое мясо, тропические регионы
    /// - Существа: укусы насекомых, контакт с инфицированными животными
    /// - Магия: проклятия паразитизма, ритуалы призыва
    Parasite,
}

/// Симптомы инфекции, влияющие на геймплей и витальные показатели.
///
/// Каждый симптом имеет числовое значение (0.0-1.0), представляющее
/// интенсивность проявления. Значения используются для:
/// - Расчёта штрафов к характеристикам и навыкам
/// - Триггеров системных событий (потеря сознания, смерть)
/// - Визуальных/звуковых эффектов в клиенте
///
/// # Шкала интенсивности
/// ```
/// 0.0-0.3 : Лёгкое проявление (косметический эффект, минимальные штрафы)
/// 0.3-0.6 : Умеренное (заметные штрафы, требуется лечение)
/// 0.6-0.9 : Тяжёлое (серьёзные штрафы, риск осложнений)
/// 0.9-1.0 : Критическое (угроза жизни, немедленное вмешательство)
/// ```
///
/// # Пример расчёта штрафа от лихорадки
/// ```rust,ignore
/// if let Some(InfectionSymptom::Fever(temp)) = infection.symptoms.iter().find(|s| matches!(s, InfectionSymptom::Fever(_))) {
///     // Каждый градус выше 37°С: -5% к навыкам, -1 к сознанию
///     let excess = (temp - 37.0).max(0.0);
///     let skill_penalty = (excess * 5.0) as i16;
///     let consciousness_penalty = excess * 0.1;
///     // Применить штрафы к персонажу...
/// }
/// ```
///
/// # Взаимодействие между симптомами
/// Некоторые симптомы усиливают друг друга:
/// - `Inflammation` + `Necrosis` = ускоренное распространение инфекции
/// - `Fever` + `SystemicShock` = экспоненциальный рост риска смерти
///
/// # Ссылки
/// - *Dwarf Fortress*: `SYNDROME` с тегами `CE_BODY_MAT_INTERACTION`, `CE_ADD_BODY_MAT_LAYER`
#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum InfectionSymptom {
    /// Повышенная температура тела (лихорадка).
    ///
    /// # Механика
    /// - Значение: температура в °С выше нормы (37.0°С)
    /// - Штрафы:
    ///   - +1°С: -5% к навыкам, -1 к сознанию
    ///   - +2°С: -15% к навыкам, -3 к сознанию, риск галлюцинаций
    ///   - +3°С и выше: автоматическая потеря сознания, риск смерти
    ///
    /// # Лечение
    /// - Жаропонижающие: снижают значение на 0.5-1.0 за применение
    /// - Охлаждение: компрессы, погружение в воду (временный эффект)
    /// - Лечение причины: снижение `virulence` инфекции
    ///
    /// # Особые эффекты
    /// - Лёгкая лихорадка (0.5-1.0°С): +10% к иммунному ответу (адаптивная реакция)
    Fever(f32),

    /// Воспалительная реакция тканей (отёк, покраснение, боль).
    ///
    /// # Механика
    /// - Значение: степень воспаления (0.0 = нет, 1.0 = максимальный отёк)
    /// - Штрафы:
    ///   - 0.3-0.6: -10% к использованию поражённой части тела
    ///   - 0.6-0.9: -30% к использованию, +20% к боли
    ///   - 0.9-1.0: полная блокировка функции части, риск некроза
    ///
    /// # Геймплейные эффекты
    /// - Визуальный: изменение спрайта/модели (покраснение, припухлость)
    /// - Тактильный: штраф к манипуляциям (взятие предметов, использование оружия)
    /// - Болевой: увеличение уровня боли, влияющего на сознание
    ///
    /// # Лечение
    /// - Противовоспалительные: снижают значение на 0.2-0.4 за применение
    /// - Покой: уменьшение нагрузки на поражённую часть ускоряет восстановление
    /// - Дренирование: хирургическое удаление экссудата (требует навыка **Surgery**)
    Inflammation(f32),

    /// Отмирание тканей (некроз, гангрена).
    ///
    /// # Механика
    /// - Значение: доля поражённой ткани (0.0 = здорова, 1.0 = полностью некротизирована)
    /// - Необратимость: при значении >0.8 ткань считается утраченной (`Missing`)
    /// - Риск распространения: 10% за игровой час при отсутствии лечения
    ///
    /// # Последствия
    /// - Потеря функции поражённой части (как `WoundSeverity::Missing`)
    /// - Токсическая нагрузка: +0.1 к концентрации токсинов в крови за каждые 0.1 некроза
    /// - Риск сепсиса: при некрозе >0.5 в критических зонах (грудь, голова)
    ///
    /// # Лечение
    /// - Хирургическая санация: удаление некротизированных тканей (останавливает прогресс)
    /// - Ампутация: крайняя мера при некрозе конечности >0.9
    /// - Магия/технологии: регенерация тканей (фэнтези/киберпанк сеттинги)
    ///
    /// # Важное замечание
    /// Некротизированная ткань не заживает естественным путём.
    /// Требуется активное вмешательство для предотвращения летального исхода.
    Necrosis(f32),

    /// Системный воспалительный ответ (сепсис, септический шок).
    ///
    /// # Механика
    /// - Значение: тяжесть шока (0.0 = нет, 1.0 = терминальная стадия)
    /// - Прогрессия:
    ///   - 0.3-0.6: тахикардия, тахипноэ, спутанность сознания
    ///   - 0.6-0.9: гипотензия, полиорганная недостаточность
    ///   - 0.9-1.0: необратимый шок, смерть в течение 1-6 часов
    ///
    /// # Штрафы
    /// - Сознание: -0.1 за каждые 0.1 шока
    /// - Характеристики: -2 к всем физическим характеристикам при шоке >0.5
    /// - Риск смерти: экспоненциальный рост при шоке >0.7
    ///
    /// # Лечение
    /// - Интенсивная терапия: требует стационара и навыка **Medicine** (Hard)
    /// - Антибиотики/антивирусы: снижение `virulence` инфекции — ключевой фактор
    /// - Поддержка витальных функций: ИВЛ, инфузионная терапия (ресурсы)
    ///
    /// # Пример из правил
    /// > "Septic shock has a mortality rate of 40-50% even with modern treatment."
    /// — Адаптировано для фэнтези: шанс выживания = (POW + CON) / 2 + medical_bonus
    SystemicShock(f32),
}

