/// Данные об активной инфекции в организме.
///
/// # Жизненный цикл инфекции
/// 1. **Инвазия**: попадание патогена в организм (ранение, вдыхание, проглатывание)
/// 2. **Инкубация**: `incubation_remaining` отсчитывается, симптомов нет
/// 3. **Проявление**: при `incubation_remaining <= 0` появляются `symptoms`
/// 4. **Прогрессия**: симптомы усиливаются, возможен системный ответ
/// 5. **Разрешение**: иммунный ответ или лечение устраняют инфекцию
///
/// # Расчёт прогрессии
/// ```rust,ignore
/// // В системе infection_progress_system
/// if infection.incubation_remaining > 0.0 {
///     infection.incubation_remaining -= immune_response * delta_hours;
/// } else {
///     // Симптомы прогрессируют
///     for symptom in &mut infection.symptoms {
///         match symptom {
///             InfectionSymptom::Fever(temp) => *temp = (*temp + 0.1).min(42.0),
///             InfectionSymptom::Necrosis(rate) => *rate += infection.virulence * 0.01,
///             // ... другие симптомы
///         }
///     }
/// }
/// ```
///
/// # Взаимодействие с иммунной системой
/// Иммунный ответ рассчитывается как:
/// ```rust,ignore
/// let base_immunity = (chars.con + chars.pow) / 2;
/// let medical_bonus = if has_treatment { 10 } else { 0 };
/// let immune_response = (base_immunity + medical_bonus) as f32 / 10.0;
/// ```
///
/// # Ссылки
/// - *Dwarf Fortress*: механика `SYNDROME`, `CE_ADD_SYNDROME_DILUTE`, `CE_BODY_MAT_INTERACTION`
/// - *CDDA*: система иммунного ответа и прогрессии заболеваний
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Infection {
    /// Тип патогена, вызвавшего инфекцию.
    ///
    /// Определяет:
    /// - Базовую `virulence` (скорость репликации)
    /// - Уязвимость к специфичному лечению
    /// - Возможные `symptoms` (не все патогены вызывают все симптомы)
    pub pathogen: PathogenId,

    /// Вирулентность патогена (0.0-1.0).
    ///
    /// Высокая вирулентность означает:
    /// - Быстрое сокращение `incubation_remaining`
    /// - Ускоренную прогрессию симптомов
    /// - Сниженную эффективность иммунного ответа
    ///
    /// # Примеры значений
    /// | Патоген | Virulence | Комментарий |
    /// |---------|-----------|-------------|
    /// | Обычная бактерия | 0.2-0.4 | Медленное развитие, легко лечится |
    /// | Вирус гриппа | 0.5-0.7 | Быстрое распространение, умеренная тяжесть |
    /// | Геморрагическая лихорадка | 0.8-1.0 | Высокая летальность, требует срочного лечения |
    ///
    /// # Модификаторы
    /// - **Мутации**: в фэнтези-сеттингах вирулентность может расти со временем
    /// - **Лечение**: антибиотики/антивирусы снижают эффективную virulence
    pub virulence: f32,

    /// Оставшееся время инкубации в игровых часах.
    ///
    /// Пока значение > 0.0:
    /// - Симптомы отсутствуют
    /// - Инфекция не передаётся другим (для контагиозных патогенов)
    /// - Иммунная система может устранить патоген без последствий
    ///
    /// При достижении 0.0:
    /// - Появляются начальные симптомы из `symptoms`
    /// - Запускается механизм прогрессии заболевания
    /// - Возможен системный ответ организма
    ///
    /// # Обновление
    /// Значение уменьшается в `infection_progress_system`:
    /// ```rust,ignore
    /// infection.incubation_remaining -= immune_response * delta_hours;
    /// ```
    pub incubation_remaining: f32,

    /// Активные симптомы инфекции.
    ///
    /// Список может содержать несколько симптомов одновременно.
    /// Интенсивность каждого симптома (внутреннее значение) обновляется
    /// независимо в зависимости от `virulence` и иммунного ответа.
    ///
    /// # Пример инициализации
    /// ```rust,ignore
    /// let symptoms = match pathogen {
    ///     PathogenId::Bacteria => vec![
    ///         InfectionSymptom::Fever(0.5),
    ///         InfectionSymptom::Inflammation(0.3),
    ///     ],
    ///     PathogenId::Virus => vec![
    ///         InfectionSymptom::Fever(1.0),
    ///         InfectionSymptom::SystemicShock(0.2),
    ///     ],
    ///     // ... другие патогены
    /// };
    /// ```
    ///
    /// # Динамика
    /// - Симптомы могут усиливаться, ослабевать или исчезать со временем
    /// - Новые симптомы могут добавляться при прогрессии заболевания
    /// - Лечение может напрямую снижать интенсивность конкретных симптомов
    pub symptoms: Vec<InfectionSymptom>,
}

